_LANG_KEY = "wv_language"


def t(key: str) -> str:
    """Return the translation for key in the active language."""
    import streamlit as st
    lang = st.session_state.get(_LANG_KEY, "es")
    entry = TRANSLATIONS.get(key)
    if entry is None:
        return key
    return entry.get(lang, entry.get("es", key))


def language_selector():
    import streamlit as st
    current = st.session_state.get(_LANG_KEY, "es")
    choice = st.selectbox(
        "\U0001f310 Idioma / Language",
        ["es", "en"],
        index=0 if current == "es" else 1,
        key="lang_selector",
    )
    if choice != current:
        st.session_state[_LANG_KEY] = choice
        st.rerun()

def get_lang() -> str:
    import streamlit as st
    return st.session_state.get(_LANG_KEY, "es")
